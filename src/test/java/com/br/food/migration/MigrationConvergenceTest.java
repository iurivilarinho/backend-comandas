package com.br.food.migration;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;

import javax.sql.DataSource;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.jdbc.core.JdbcTemplate;

import com.br.food.FoodApplication;

/**
 * CMD-016. Proves that the migrations and the JPA entities describe the same schema, on a brand new database and on a
 * database built the old way (Hibernate {@code ddl-auto=update}, no Flyway) that has the shape it had before CMD-015.
 *
 * <p>
 * The application boots with the real {@code src/main/resources/application.properties} (Flyway baseline at 1, run by
 * the platform starter in the own-instance edition, {@code CENTRAL_MODE=off}), so the production configuration is what is
 * tested. The reference schema is what Hibernate itself generates from the entities.
 */
class MigrationConvergenceTest {

	private static final Path MAIN_PROPERTIES = Path.of("src/main/resources/application.properties");
	private static final Path V2_SCRIPT = Path.of("src/main/resources/db/migration/V2__reconcile_existing_databases.sql");

	private static List<String> entitySchema;

	@BeforeAll
	static void buildEntityReferenceSchema() throws Exception {
		String url = EmbeddedPostgresSupport.createDatabase("entities");
		// No migrations at all: Hibernate builds the schema from the entities.
		try (ConfigurableApplicationContext ctx = boot(url, "--spring.flyway.locations=classpath:db/none",
				"--spring.jpa.hibernate.ddl-auto=create")) {
			entitySchema = snapshot(ctx.getBean(DataSource.class));
		}
		assertThat(entitySchema).as("schema generated by Hibernate").hasSizeGreaterThan(100);
	}

	@Test
	void emptyDatabaseIsBuiltByMigrationsAndMatchesTheEntities() throws Exception {
		String url = EmbeddedPostgresSupport.createDatabase("fresh");

		try (ConfigurableApplicationContext ctx = boot(url)) {
			DataSource ds = ctx.getBean(DataSource.class);
			JdbcTemplate jdbc = new JdbcTemplate(ds);

			assertThat(jdbc.queryForList(
					"SELECT version || ':' || type FROM flyway_schema_history WHERE success ORDER BY installed_rank",
					String.class)).containsExactly("1:SQL", "2:SQL");
			assertThat(snapshot(ds)).isEqualTo(entitySchema);

			// The seed runs on top of the migrations: base data and the administrator role with a readable name.
			assertThat(jdbc.queryForObject("SELECT count(*) FROM roles WHERE nome = 'ROLE_ADMIN'", Integer.class))
					.isEqualTo(1);
			assertThat(jdbc.queryForObject("SELECT count(*) FROM payment_methods", Integer.class)).isPositive();
			// No admin user without APP_ADMIN_PASSWORD (CMD-015).
			assertThat(jdbc.queryForObject("SELECT count(*) FROM users", Integer.class)).isZero();
		}
	}

	@Test
	void databaseBuiltByDdlAutoUpdateIsBaselinedAndConvergesToTheEntities() throws Exception {
		String url = EmbeddedPostgresSupport.createDatabase("legacy");
		DataSource ds = EmbeddedPostgresSupport.dataSource(url);
		try (ConfigurableApplicationContext ctx = boot(url, "--spring.flyway.locations=classpath:db/none",
				"--spring.jpa.hibernate.ddl-auto=create")) {
			// the schema is created; now give it the shape of the last production build
		}
		JdbcTemplate jdbc = new JdbcTemplate(ds);
		runStatements(ds, "ALTER TABLE dining_tables DROP COLUMN access_version",
				"ALTER TABLE tbrecoverypassword ALTER COLUMN code TYPE varchar(4)",
				"ALTER TABLE orders DROP CONSTRAINT orders_channel_check",
				"ALTER TABLE orders ADD CONSTRAINT orders_channel_check CHECK (channel IN ('DINE_IN', 'DELIVERY'))",
				"DELETE FROM flyway_schema_history", "DROP TABLE flyway_schema_history");
		jdbc.update("DELETE FROM roles");
		jdbc.update("INSERT INTO roles (status, description, nome) VALUES (true, 'ROLE_ADMIN', NULL)");
		jdbc.update("INSERT INTO dining_tables (table_number, active, occupied) VALUES ('1', true, false)");
		assertThat(snapshot(ds)).isNotEqualTo(entitySchema);

		try (ConfigurableApplicationContext ctx = boot(url)) {
			assertThat(jdbc.queryForList(
					"SELECT version || ':' || type FROM flyway_schema_history WHERE success ORDER BY installed_rank",
					String.class)).containsExactly("1:BASELINE", "2:SQL");
			assertThat(snapshot(ds)).isEqualTo(entitySchema);

			// existing data survives; the old administrator role is found by its name now instead of duplicated
			assertThat(jdbc.queryForObject("SELECT count(*) FROM dining_tables WHERE access_version = 1",
					Integer.class)).isEqualTo(1);
			assertThat(jdbc.queryForObject("SELECT count(*) FROM roles", Integer.class)).isEqualTo(1);
			assertThat(jdbc.queryForObject("SELECT nome FROM roles", String.class)).isEqualTo("ROLE_ADMIN");

			// V2 is idempotent: running it again changes nothing and does not fail.
			List<String> after = snapshot(ds);
			runScript(ds, V2_SCRIPT);
			runScript(ds, V2_SCRIPT);
			assertThat(snapshot(ds)).isEqualTo(after);
		}
	}

	private static ConfigurableApplicationContext boot(String jdbcUrl, String... overrides) {
		String[] base = { "--spring.config.location=file:" + MAIN_PROPERTIES, "--spring.datasource.url=" + jdbcUrl,
				"--spring.datasource.username=postgres", "--spring.datasource.password=", "--server.port=0",
				"--spring.main.banner-mode=off",
				// Required settings have no default in application.properties; these are dummy test values.
				"--spring.mail.username=test@example.com", "--spring.mail.password=test",
				// Hosting platform: the own-instance edition keeps the single instance on the public schema.
				"--CENTRAL_MODE=off", "--JWT_SECRET=test-only-jwt-secret-not-for-production-0123456789" };
		String[] args = new String[base.length + overrides.length];
		System.arraycopy(base, 0, args, 0, base.length);
		System.arraycopy(overrides, 0, args, base.length, overrides.length);
		return new SpringApplicationBuilder(FoodApplication.class).run(args);
	}

	private static List<String> snapshot(DataSource ds) throws Exception {
		try (Connection c = ds.getConnection()) {
			return SchemaSnapshot.take(c);
		}
	}

	private static void runStatements(DataSource ds, String... statements) throws Exception {
		try (Connection c = ds.getConnection(); Statement st = c.createStatement()) {
			for (String sql : statements) {
				st.execute(sql);
			}
		}
	}

	private static void runScript(DataSource ds, Path script) throws Exception {
		String sql = Files.readString(script, StandardCharsets.UTF_8);
		try (Connection c = ds.getConnection()) {
			c.setAutoCommit(false);
			try (Statement st = c.createStatement()) {
				st.execute(sql); // the PostgreSQL driver parses dollar quoting and sends the script as a whole
			}
			c.commit();
		}
	}
}
